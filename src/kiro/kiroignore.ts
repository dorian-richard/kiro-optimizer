// .kiroignore suggestions: tracked files that are pure token sinks for an agent (lockfiles, bundles,
// source maps, generated code, snapshots, vendored code, committed build outputs, large data files,
// binary assets). .kiroignore blocks direct reads AND filters grep/file-search results at zero turn
// cost, so it is the first enforcement layer. Regular source files and build configuration are never
// matched: patterns are either specific extensions/basenames or anchored directories / files.

import { execFileSync } from 'node:child_process';
import { closeSync, openSync, readdirSync, readSync, statSync } from 'node:fs';
import { join } from 'node:path';

export interface KiroignoreSuggestion {
  patterns: string[];
  reasons: Record<string, string>;
}

const LOCKFILES = new Set([
  'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lockb', 'bun.lock', 'Cargo.lock',
  'poetry.lock', 'Pipfile.lock', 'uv.lock', 'pdm.lock', 'composer.lock', 'Gemfile.lock', 'go.sum', 'gradle.lockfile',
  'packages.lock.json', 'paket.lock', 'mix.lock', 'pubspec.lock', 'Podfile.lock', 'Package.resolved', 'flake.lock',
  'conda-lock.yml', 'deno.lock',
]);

/** Build configuration and specs an agent may need: never excluded, whatever their size. */
const PROTECTED_RE = new RegExp([
  '^(pom\\.xml|build\\.gradle(\\.kts)?|settings\\.gradle(\\.kts)?|gradle\\.properties|package\\.json|jsconfig\\.json',
  'tsconfig.*\\.json|.*\\.(csproj|fsproj|vbproj|sln|props|targets)|Directory\\.Build\\..*|Dockerfile.*|docker-compose.*\\.ya?ml',
  'Makefile|CMakeLists\\.txt|go\\.mod|Cargo\\.toml|pyproject\\.toml|setup\\.(py|cfg)|requirements.*\\.txt|Gemfile|composer\\.json',
  'angular\\.json|nx\\.json|project\\.json|workspace\\.json|turbo\\.json|lerna\\.json|cdk\\.json|appsettings.*\\.json',
  'application.*\\.(ya?ml|properties)|web\\.config|serverless\\.ya?ml|template\\.ya?ml|.*\\.tf)$',
].join('|'), 'i');
/** API / schema / migration files are sources of truth even when large. */
const PROTECTED_PATH_RE = /(openapi|swagger|schema|migration|\.kiro\/|\.github\/)/i;

const DATA_EXT = new Set(['csv', 'tsv', 'json', 'jsonl', 'ndjson', 'geojson', 'xml', 'sql', 'dump', 'log']);
const DATA_LIMIT = 200 * 1024;

// Binary assets agents never read. Raster images are left out on purpose: the read tool can show them.
const BINARY_EXT = new Set([
  'woff', 'woff2', 'ttf', 'otf', 'eot', 'mp3', 'mp4', 'wav', 'ogg', 'flac', 'mov', 'avi', 'mkv', 'webm', 'zip', 'tar',
  'gz', 'tgz', 'bz2', 'xz', '7z', 'rar', 'jar', 'war', 'ear', 'aar', 'class', 'pyc', 'pyo', 'o', 'obj', 'a', 'lib', 'so',
  'dylib', 'dll', 'exe', 'pdb', 'wasm', 'pdf', 'doc', 'docx', 'xls', 'xlsx', 'ppt', 'pptx', 'sqlite', 'sqlite3', 'db',
  'mdb', 'psd', 'ai', 'sketch', 'fig', 'parquet', 'avro', 'orc', 'pkl', 'npy', 'npz', 'h5', 'onnx', 'pt', 'bin',
]);

const OUTPUT_DIRS_STRONG = new Set([
  'dist', 'target', 'out', 'obj', '.next', '.nuxt', 'coverage', '__pycache__', '.gradle', '.terraform', '.pytest_cache',
  '.mypy_cache', '.svelte-kit', '.angular', '.turbo', '.parcel-cache', 'storybook-static',
]);
const OUTPUT_DIRS_WEAK = new Set(['build', 'bin']);
const ARTIFACT_RE = /\.(class|jar|war|pyc|o|obj|so|dll|exe|a|lib|pdb|map|wasm|dylib|bin)$|[.-]min\.(m?js|css)$|\.(bundle|chunk)\.m?js$/i;
/** An output-dir name below one of these is a source package (e.g. Java com/acme/target), not an output. */
const SOURCE_ROOTS = new Set(['src', 'main', 'java', 'kotlin', 'scala', 'lib', 'app', 'test', 'tests', 'internal', 'pkg', 'cmd', 'com', 'org', 'net', 'io']);
const VENDOR_DIRS = new Set(['vendor', 'third_party', 'third-party', 'thirdparty', 'node_modules', 'bower_components']);
const GENERATED_DIRS = new Set(['generated', '__generated__', 'gen', 'generated-sources', 'generated-src', 'autogen']);
const GENERATED_MARKER = /@generated|do not edit|auto-?generated|autogenerated|code generated by|generated by|this file was generated/i;
const GENERATED_SUFFIXES = ['.pb.go', '_pb2.py', '_pb2_grpc.py', '.pb.cc', '.pb.h', '.g.cs', '.g.dart', '.freezed.dart', '.generated.ts', '.generated.js', '.generated.cs'];
const MINIFIED_NAME_RE = /([.-]min|\.bundle|\.chunk)\.(m?js|cjs|css)$/i;
const SOURCEMAP_RE = /\.(m?js|cjs|css)\.map$/i;
const MAX_FILE_PATTERNS = 100;

function ext(path: string): string {
  const b = path.slice(path.lastIndexOf('/') + 1);
  const i = b.lastIndexOf('.');
  return i > 0 ? b.slice(i + 1).toLowerCase() : '';
}

function base(path: string): string {
  return path.slice(path.lastIndexOf('/') + 1);
}

function headBytes(abs: string, n: number): Buffer {
  const fd = openSync(abs, 'r');
  try {
    const buf = Buffer.alloc(n);
    return buf.subarray(0, readSync(fd, buf, 0, n, 0));
  } finally {
    closeSync(fd);
  }
}

function sizeOf(abs: string): number {
  try { return statSync(abs).size; } catch { return -1; }
}

function fmtBytes(n: number): string {
  return n >= 1 << 20 ? `${(n / (1 << 20)).toFixed(1)} MB` : `${Math.max(1, Math.round(n / 1024))} KB`;
}

/** Tracked files (git ls-files), or a bounded walk when the root is not a git checkout. */
export function listRepoFiles(root: string, cap = 300_000): string[] {
  try {
    const out = execFileSync('git', ['-C', root, 'ls-files', '-z', '--cached'], {
      maxBuffer: 1 << 29, timeout: 60_000, stdio: ['ignore', 'pipe', 'ignore'], windowsHide: true,
    });
    return out.toString('utf8').split('\0').filter(Boolean).slice(0, cap);
  } catch {
    const files: string[] = [];
    const skip = new Set(['.git', 'node_modules', '.kopt', '.hg', '.svn']);
    const walk = (rel: string) => {
      if (files.length >= cap) return;
      let entries;
      try { entries = readdirSync(join(root, rel), { withFileTypes: true }); } catch { return; }
      for (const e of entries) {
        const p = rel ? `${rel}/${e.name}` : e.name;
        if (e.isDirectory()) { if (!skip.has(e.name)) walk(p); }
        else if (e.isFile()) files.push(p);
        if (files.length >= cap) return;
      }
    };
    walk('');
    return files;
  }
}

/**
 * Anchored `/dir/` patterns; many dirs of one name collapse into `name/`, but only when no other
 * tracked directory of that name exists (gitignore matching is case-insensitive in Kiro's `ignore`).
 */
function dirPatterns(dirs: Map<string, number>, files: string[], many = 10): Map<string, string[]> {
  const byName = new Map<string, string[]>();
  for (const d of dirs.keys()) {
    const name = base(d);
    byName.set(name, [...(byName.get(name) ?? []), d]);
  }
  const out = new Map<string, string[]>();
  for (const [name, list] of byName) {
    if (list.length > many && collapsible(name, list, files)) out.set(`${name}/`, list);
    else for (const d of list) out.set(`/${d}/`, [d]);
  }
  return out;
}

function collapsible(name: string, accepted: string[], files: string[]): boolean {
  const lname = name.toLowerCase();
  const prefixes = accepted.map((d) => d + '/');
  for (const f of files) {
    const segs = f.split('/');
    for (let i = 0; i < segs.length - 1; i++) {
      if (segs[i].toLowerCase() !== lname) continue;
      const dir = segs.slice(0, i + 1).join('/') + '/';
      if (!prefixes.some((p) => dir.startsWith(p))) return false;
    }
  }
  return true;
}

export async function suggestKiroignore(root: string): Promise<KiroignoreSuggestion> {
  const files = listRepoFiles(root);
  const reasons: Record<string, string> = {};
  const ordered: string[] = [];
  const add = (pattern: string, reason: string) => {
    if (reasons[pattern]) return;
    reasons[pattern] = reason;
    ordered.push(pattern);
  };

  const lock = new Map<string, string[]>();
  const minNames = new Map<string, number>();
  const maps = new Map<string, number>();
  const snaps = new Map<string, number>();
  let snapFiles = 0;
  const genSuffix = new Map<string, number>();
  const vendor = new Map<string, number>();
  const genDirs = new Map<string, string[]>();
  const outDirs = new Map<string, { files: string[]; artifacts: number; strong: boolean }>();
  const binary = new Map<string, number>();
  const dataCandidates: string[] = [];
  const jsCandidates: string[] = [];

  for (const f of files) {
    if (f.startsWith('.kiro/')) continue;
    const segs = f.split('/');
    const b = segs[segs.length - 1];
    const e = ext(f);

    // directory-level categories: the outermost matching directory wins
    let claimed = false;
    for (let i = 0; i < segs.length - 1 && !claimed; i++) {
      const seg = segs[i];
      const dir = segs.slice(0, i + 1).join('/');
      if (VENDOR_DIRS.has(seg.toLowerCase())) { vendor.set(dir, (vendor.get(dir) ?? 0) + 1); claimed = true; }
      else if (seg === '__snapshots__') { snaps.set(dir, (snaps.get(dir) ?? 0) + 1); claimed = true; }
      else if ((OUTPUT_DIRS_STRONG.has(seg) || OUTPUT_DIRS_WEAK.has(seg)) && !segs.slice(0, i).some((x) => SOURCE_ROOTS.has(x.toLowerCase()))) {
        const o = outDirs.get(dir) ?? { files: [], artifacts: 0, strong: OUTPUT_DIRS_STRONG.has(seg) };
        o.files.push(f);
        if (ARTIFACT_RE.test(b) || BINARY_EXT.has(e)) o.artifacts++;
        outDirs.set(dir, o);
        claimed = true;
      } else if (GENERATED_DIRS.has(seg.toLowerCase())) {
        genDirs.set(dir, [...(genDirs.get(dir) ?? []), f]);
        claimed = true;
      }
    }
    if (claimed) continue;

    if (LOCKFILES.has(b)) {
      lock.set(b, [...(lock.get(b) ?? []), f]);
      continue;
    }
    const mm = MINIFIED_NAME_RE.exec(b);
    if (mm) { const p = `*${mm[0]}`; minNames.set(p, (minNames.get(p) ?? 0) + 1); continue; }
    const sm = SOURCEMAP_RE.exec(b);
    if (sm) { const p = `*${sm[0]}`; maps.set(p, (maps.get(p) ?? 0) + 1); continue; }
    if (e === 'snap') { snapFiles++; continue; }
    const gs = GENERATED_SUFFIXES.find((s) => b.endsWith(s));
    if (gs) { genSuffix.set(`*${gs}`, (genSuffix.get(`*${gs}`) ?? 0) + 1); continue; }
    if (BINARY_EXT.has(e)) { binary.set(e, (binary.get(e) ?? 0) + 1); continue; }
    if (PROTECTED_RE.test(b) || PROTECTED_PATH_RE.test(f)) continue;
    if (DATA_EXT.has(e)) dataCandidates.push(f);
    else if (e === 'js' || e === 'mjs' || e === 'cjs' || e === 'css') jsCandidates.push(f);
  }

  // 1. lockfiles
  for (const [name, paths] of [...lock.entries()].sort()) {
    const bytes = paths.reduce((a, f) => a + Math.max(0, sizeOf(join(root, f))), 0);
    add(name, `lockfile (${paths.length} file${paths.length > 1 ? 's' : ''}, ${fmtBytes(bytes)})`);
  }
  // 2. minified bundles and source maps
  for (const [p, n] of [...minNames.entries()].sort()) add(p, `minified/bundled code (${n} files)`);
  const minified: { path: string; size: number }[] = [];
  for (const f of jsCandidates) {
    const size = sizeOf(join(root, f));
    if (size < 50 * 1024) continue;
    try {
      const head = headBytes(join(root, f), 32 * 1024);
      let nl = 0;
      for (let i = head.indexOf(10); i !== -1; i = head.indexOf(10, i + 1)) nl++;
      if (head.length / (nl + 1) > 500) minified.push({ path: f, size });
    } catch { /* unreadable */ }
    if (minified.length >= MAX_FILE_PATTERNS) break;
  }
  for (const m of minified.sort((a, b) => a.path.localeCompare(b.path))) add(`/${m.path}`, `minified bundle (${fmtBytes(m.size)}, very long lines)`);
  for (const [p, n] of [...maps.entries()].sort()) add(p, `source maps (${n} files)`);
  // 3. generated code
  for (const [p, n] of [...genSuffix.entries()].sort()) add(p, `generated code by naming convention (${n} files)`);
  const genAccepted = new Map<string, number>();
  for (const [dir, list] of genDirs) {
    if (base(dir) === '__generated__') { genAccepted.set(dir, list.length); continue; }
    const sample = list.filter((f) => !BINARY_EXT.has(ext(f))).slice(0, 8);
    let marked = 0;
    for (const f of sample) {
      try { if (GENERATED_MARKER.test(headBytes(join(root, f), 1024).toString('utf8'))) marked++; } catch { /* skip */ }
    }
    if (sample.length && marked * 2 >= sample.length) genAccepted.set(dir, list.length);
  }
  for (const [p, dirs] of [...dirPatterns(genAccepted, files).entries()].sort()) {
    const n = dirs.reduce((a, d) => a + (genAccepted.get(d) ?? 0), 0);
    add(p, `generated code (${n} files, generated markers in headers)`);
  }
  // 4. snapshots
  if (snaps.size) {
    for (const [p, dirs] of [...dirPatterns(snaps, files, 3).entries()].sort()) {
      add(p, `test snapshots (${dirs.reduce((a, d) => a + (snaps.get(d) ?? 0), 0)} files)`);
    }
  }
  if (snapFiles) add('*.snap', `test snapshots (${snapFiles} files)`);
  // 5. vendored code
  for (const [p, dirs] of [...dirPatterns(vendor, files).entries()].sort()) {
    add(p, `vendored third-party code (${dirs.reduce((a, d) => a + (vendor.get(d) ?? 0), 0)} files)`);
  }
  // 6. committed build outputs
  const outAccepted = new Map<string, number>();
  for (const [dir, o] of outDirs) {
    if (o.strong || o.artifacts * 2 >= o.files.length) outAccepted.set(dir, o.files.length);
  }
  for (const [p, dirs] of [...dirPatterns(outAccepted, files).entries()].sort()) {
    add(p, `committed build output (${dirs.reduce((a, d) => a + (outAccepted.get(d) ?? 0), 0)} files)`);
  }
  // 7. binary assets
  for (const [e, n] of [...binary.entries()].sort()) add(`*.${e}`, `binary asset (${n} files)`);
  // 8. large data files
  const big: { path: string; size: number }[] = [];
  for (const f of dataCandidates) {
    const size = sizeOf(join(root, f));
    if (size > DATA_LIMIT) big.push({ path: f, size });
  }
  big.sort((a, b) => b.size - a.size);
  const byDir = new Map<string, { path: string; size: number }[]>();
  for (const x of big) {
    const d = x.path.includes('/') ? x.path.slice(0, x.path.lastIndexOf('/')) : '';
    byDir.set(d, [...(byDir.get(d) ?? []), x]);
  }
  const dataPatterns: [string, string][] = [];
  for (const [dir, list] of byDir) {
    // a directory made only of data files collapses to one pattern
    const onlyData = () => files.every((f) => !f.startsWith(dir + '/') || f.slice(dir.length + 1).includes('/') || DATA_EXT.has(ext(f)));
    if (dir && list.length >= 5 && onlyData()) {
      dataPatterns.push([`/${dir}/`, `large data files (${list.length} files, ${fmtBytes(list.reduce((a, x) => a + x.size, 0))})`]);
    } else {
      for (const x of list) dataPatterns.push([`/${x.path}`, `large data file (${fmtBytes(x.size)})`]);
    }
  }
  for (const [p, r] of dataPatterns.slice(0, MAX_FILE_PATTERNS).sort((a, b) => a[0].localeCompare(b[0]))) add(p, r);

  return { patterns: ordered, reasons };
}

export const KIROIGNORE_BEGIN = '# >>> kopt (generated)';
export const KIROIGNORE_END = '# <<< kopt';

/** The marked block (patterns preceded by their reason as comments). */
export function kiroignoreBlock(s: KiroignoreSuggestion): string {
  const lines = [`${KIROIGNORE_BEGIN} - token sinks for agents; regenerated by \`kopt setup\` / \`kopt init\`, edit outside this block`];
  let last = '';
  for (const p of s.patterns) {
    const r = (s.reasons[p] ?? '').replace(/\s*\(.*\)$/, '');
    if (r && r !== last) lines.push(`# ${r}`);
    last = r;
    lines.push(p);
  }
  lines.push(KIROIGNORE_END);
  return lines.join('\n') + '\n';
}

/** Insert or replace the kopt block in an ignore file's text. */
export function mergeKiroignore(existing: string | undefined, block: string): string {
  const text = existing ?? '';
  const start = text.indexOf(KIROIGNORE_BEGIN);
  const endIdx = start >= 0 ? text.indexOf(KIROIGNORE_END, start) : -1;
  if (start >= 0 && endIdx >= 0) {
    const lineEnd = text.indexOf('\n', endIdx);
    const after = lineEnd < 0 ? '' : text.slice(lineEnd + 1);
    return text.slice(0, start) + block + after;
  }
  if (!text.trim()) return block;
  return text + (text.endsWith('\n') ? '' : '\n') + '\n' + block;
}

/** Remove kopt's marked block (and the blank line kopt added before it). Undefined when there is no block. */
export function removeKiroignoreBlock(existing: string | undefined): string | undefined {
  const text = existing ?? '';
  const start = text.indexOf(KIROIGNORE_BEGIN);
  const endIdx = start >= 0 ? text.indexOf(KIROIGNORE_END, start) : -1;
  if (start < 0 || endIdx < 0) return undefined;
  const lineEnd = text.indexOf('\n', endIdx);
  const before = text.slice(0, start).replace(/\n\n$/, '\n');
  const after = lineEnd < 0 ? '' : text.slice(lineEnd + 1);
  return before + after;
}
