import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import ignore from 'ignore';
import { installKiro, suggestKiroignore, mergeKiroignore, kiroignoreBlock, AUTO_APPROVE, MCP_TIMEOUTS, hookCommand } from '../src/kiro/index.js';
import { ensureArrayValue, parseJsonc } from '../src/kiro/jsonc.js';
import { shellArg, stableNodePath } from '../src/kiro/command.js';

// KOPT_HOOK_COMMAND=node: the absolute path of the running Node on every OS (Kiro started from the Dock or the Start
// menu has no shell-profile PATH).
const NODE = stableNodePath(process.execPath);
const nodeLine = (bin: string) => `${shellArg(NODE)} ${shellArg(bin)}`;

let tmp: string;
const saved: Record<string, string | undefined> = {};
const ENV = ['KOPT_HOME', 'KOPT_KIRO_HOME', 'KOPT_KIRO_USER_SETTINGS', 'KOPT_CLI', 'KOPT_HOOK_COMMAND', 'KOPT_KIRO_CLI', 'KOPT_KIRO_IDE_PATHS',
  'KOPT_CACHE_DIR', 'KIRO_HOME'];
let cli: string;

function write(root: string, rel: string, content: string | Buffer): void {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content);
}

function git(root: string, ...args: string[]): void {
  execFileSync('git', ['-C', root, ...args], { stdio: 'ignore' });
}

function hasGit(): boolean {
  try { execFileSync('git', ['--version'], { stdio: 'ignore' }); return true; } catch { return false; }
}

function newRepo(name: string): string {
  const root = join(tmp, name);
  mkdirSync(root, { recursive: true });
  if (hasGit()) git(root, 'init', '-q');
  else mkdirSync(join(root, '.git'));
  write(root, 'src/app.ts', 'export const app = 1;\n');
  write(root, 'package.json', '{"name":"x"}\n');
  return root;
}

const read = (p: string) => readFileSync(p, 'utf8');
const json = (p: string) => JSON.parse(read(p));

beforeAll(() => {
  tmp = mkdtempSync(join(tmpdir(), 'kopt-kiro-'));
  for (const k of ENV) saved[k] = process.env[k];
  cli = join(tmp, 'pkg', 'dist', 'cli.js');
  mkdirSync(dirname(cli), { recursive: true });
  writeFileSync(cli, '// fake cli\n');
});

beforeEach(() => {
  for (const k of ENV) delete process.env[k];
  process.env.KOPT_HOME = join(tmp, 'user-home', '.kopt');
  process.env.KOPT_KIRO_HOME = join(tmp, 'user-home', '.kiro');
  process.env.KOPT_KIRO_USER_SETTINGS = join(tmp, 'user-home', 'Kiro', 'User', 'settings.json');
  process.env.KOPT_CLI = cli;
  // deterministic command form, and never detect (or run) the developer's real Kiro installs
  process.env.KOPT_HOOK_COMMAND = 'node';
  process.env.KOPT_KIRO_CLI = 'none';
  process.env.KOPT_KIRO_IDE_PATHS = '';
  process.env.KOPT_CACHE_DIR = join(tmp, 'cache');
});

afterAll(() => {
  for (const k of ENV) {
    if (saved[k] === undefined) delete process.env[k];
    else process.env[k] = saved[k];
  }
  rmSync(tmp, { recursive: true, force: true });
});

describe('suggestKiroignore', () => {
  it('excludes token sinks and never regular sources or build configuration', async () => {
    const root = newRepo('suggest');
    const files: Record<string, string | Buffer> = {
      'package-lock.json': '{}', 'go.sum': 'x', 'pom.xml': '<project/>', 'tsconfig.base.json': '{}',
      'public/vendor.min.js': 'x', 'public/vendor.min.js.map': '{}', 'assets/app.bundle.js': 'x',
      'web/legacy.js': 'var a=1;'.repeat(15000),
      'dist/app.js': 'x', 'dist/app.js.map': '{}', 'dist/package.json': '{}',
      'src/main/java/com/acme/target/Foo.java': 'class Foo {}',
      'build/scripts/release.sh': 'echo hi', 'build/README.md': '# build',
      'bin/tool.jar': Buffer.from([0, 1]), 'bin/other.jar': Buffer.from([0, 1]),
      'src/__generated__/graphql.ts': 'export type A = 1;',
      'api/gen/client.go': '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n',
      'api/gen/types.go': '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n',
      'tools/gen/generator.ts': 'export function generate() {}\n',
      'src/components/__snapshots__/Button.test.tsx.snap': 'exports[`a`] = 1;',
      'vendor/github.com/x/y/y.go': 'package y',
      'data/big.csv': 'a,b\n'.repeat(80_000), 'data/small.csv': 'a,b\n',
      'fixtures/huge.json': JSON.stringify({ x: 'y'.repeat(300_000) }),
      'docs/openapi.json': JSON.stringify({ x: 'y'.repeat(300_000) }),
      'db/migration/V1__init.sql': 'create table t(a int);\n'.repeat(20_000),
      'fonts/a.woff2': Buffer.from([0, 1, 2]), 'img/logo.png': Buffer.from([137, 80]),
      'proto/api.pb.go': '// Code generated\npackage proto',
      'Dockerfile': 'FROM node', 'build.gradle': 'plugins {}', 'Service.csproj': '<Project/>',
    };
    for (const [p, c] of Object.entries(files)) write(root, p, c);
    if (hasGit()) git(root, 'add', '-A');

    const s = await suggestKiroignore(root);
    const ig = ignore().add(s.patterns);
    const ignored = (p: string) => ig.ignores(p);
    for (const p of [
      'package-lock.json', 'go.sum', 'public/vendor.min.js', 'public/vendor.min.js.map', 'assets/app.bundle.js', 'web/legacy.js',
      'dist/app.js', 'dist/package.json', 'bin/tool.jar', 'src/__generated__/graphql.ts', 'api/gen/client.go',
      'src/components/__snapshots__/Button.test.tsx.snap', 'vendor/github.com/x/y/y.go', 'data/big.csv', 'fixtures/huge.json',
      'fonts/a.woff2', 'proto/api.pb.go',
    ]) expect(ignored(p), p).toBe(true);
    for (const p of [
      'src/app.ts', 'package.json', 'pom.xml', 'tsconfig.base.json', 'Dockerfile', 'build.gradle', 'Service.csproj',
      'src/main/java/com/acme/target/Foo.java', 'build/scripts/release.sh', 'tools/gen/generator.ts', 'data/small.csv',
      'docs/openapi.json', 'db/migration/V1__init.sql', 'img/logo.png',
    ]) expect(ignored(p), p).toBe(false);
    for (const p of s.patterns) expect(s.reasons[p], p).toBeTruthy();
    expect(s.reasons['/data/big.csv']).toMatch(/large data file/);
    expect(s.reasons['package-lock.json']).toMatch(/^lockfile/);
    // deterministic
    expect((await suggestKiroignore(root)).patterns).toEqual(s.patterns);
  });

  it('collapses many output dirs into one pattern only when no source dir shares the name', async () => {
    const root = newRepo('collapse');
    for (let i = 0; i < 12; i++) write(root, `svc${i}/target/classes/A.class`, Buffer.from([0xca, 0xfe]));
    write(root, 'web/node_modules/react/index.js', 'x');
    if (hasGit()) git(root, 'add', '-A');
    const s1 = await suggestKiroignore(root);
    expect(s1.patterns).toContain('target/');
    expect(s1.reasons['/web/node_modules/']).toMatch(/vendored/);
    write(root, 'svc0/src/main/java/com/acme/target/Foo.java', 'class Foo {}');
    write(root, 'lib/target/Bar.java', 'class Bar {}');
    if (hasGit()) git(root, 'add', '-A');
    const s2 = await suggestKiroignore(root);
    expect(s2.patterns).not.toContain('target/');
    const ig = ignore().add(s2.patterns);
    expect(ig.ignores('svc3/target/classes/A.class')).toBe(true);
    expect(ig.ignores('svc0/src/main/java/com/acme/target/Foo.java')).toBe(false);
    expect(ig.ignores('lib/target/Bar.java')).toBe(false);
  });

  it('merges a marked block into an existing ignore file idempotently', () => {
    const block = kiroignoreBlock({ patterns: ['yarn.lock', '*.min.js'], reasons: { 'yarn.lock': 'lockfile (1 file, 2 KB)', '*.min.js': 'minified/bundled code (3 files)' } });
    expect(block).toContain('# lockfile\nyarn.lock\n# minified/bundled code\n*.min.js\n# <<< kopt\n');
    const user = '# secrets\n.env\n';
    const once = mergeKiroignore(user, block);
    expect(once.startsWith(user)).toBe(true);
    expect(mergeKiroignore(once, block)).toBe(once);
    const block2 = kiroignoreBlock({ patterns: ['go.sum'], reasons: { 'go.sum': 'lockfile' } });
    const replaced = mergeKiroignore(once + 'after\n', block2);
    expect(replaced).toContain('go.sum');
    expect(replaced).not.toContain('yarn.lock');
    expect(replaced.endsWith('after\n')).toBe(true);
  });
});

describe('jsonc settings edits', () => {
  it('adds .kiroignore to kiroAgent.agentIgnoreFiles without losing comments', () => {
    const key = 'kiroAgent.agentIgnoreFiles';
    expect(JSON.parse(ensureArrayValue(undefined, key, '.kiroignore')!)).toEqual({ [key]: ['.kiroignore'] });
    expect(JSON.parse(ensureArrayValue('{\n  "a": 1\n}\n', key, '.kiroignore')!)).toEqual({ a: 1, [key]: ['.kiroignore'] });
    expect(ensureArrayValue(`{"${key}": [".kiroignore"]}`, key, '.kiroignore')).toBeUndefined();
    const withComments = '// my settings\n{\n  // font\n  "editor.fontSize": 14, /* x */\n}\n';
    const out = ensureArrayValue(withComments, key, '.kiroignore')!;
    expect(out).toContain('// my settings');
    expect(out).toContain('/* x */');
    expect(parseJsonc(out)).toEqual({ [key]: ['.kiroignore'], 'editor.fontSize': 14 });
    const existing = `{\n  // c\n  "${key}": [".gitignore"],\n}`;
    expect(parseJsonc(ensureArrayValue(existing, key, '.kiroignore')!)).toEqual({ [key]: ['.kiroignore', '.gitignore'] });
    expect(parseJsonc(ensureArrayValue('// c\n{}', key, '.kiroignore')!)).toEqual({ [key]: ['.kiroignore'] });
    expect(() => ensureArrayValue('[1,2]', key, '.kiroignore')).toThrow();
  });
});

describe('installKiro', () => {
  it('installs into a workspace, merging with existing configuration', async () => {
    const root = newRepo('ws');
    write(root, 'yarn.lock', '# lock');
    write(root, '.kiro/settings/mcp.json', JSON.stringify({ mcpServers: { github: { url: 'https://api.github.com/mcp' } } }, null, 2));
    write(root, '.kiroignore', '# secrets\n.env\n');
    write(root, '.gitignore', 'node_modules/');
    write(root, '.vscode/settings.json', '{\n  // keep me\n  "editor.tabSize": 2\n}\n');
    if (hasGit()) git(root, 'add', '-A');

    const r = await installKiro({ root, scope: 'workspace' });
    const k = join(root, '.kiro');
    for (const p of [
      join(k, 'settings', 'mcp.json'), join(k, 'steering', 'kopt.md'), join(k, 'steering', 'kopt-specs.md'),
      join(k, 'hooks', 'kopt.json'), join(k, 'agents', 'kopt-explorer.json'), join(root, '.kiroignore'),
      join(root, '.vscode', 'settings.json'),
    ]) expect(r.written, p).toContain(p);

    const mcp = json(join(k, 'settings', 'mcp.json'));
    expect(mcp.mcpServers.github).toEqual({ url: 'https://api.github.com/mcp' });
    expect(mcp.mcpServers.kopt).toEqual({ command: NODE, args: [cli, 'mcp', '--root', root], autoApprove: AUTO_APPROVE, ...MCP_TIMEOUTS });
    expect(mcp.mcpServers.kopt.autoApprove).not.toContain('kopt_run');

    const hooks = json(join(k, 'hooks', 'kopt.json'));
    expect(hooks.version).toBe('v1');
    expect(hooks.hooks.map((h: any) => h.trigger)).toEqual(['SessionStart', 'UserPromptSubmit', 'PreToolUse', 'PostToolUse', 'PostFileSave', 'PostFileCreate', 'PostFileDelete', 'Stop']);
    for (const h of hooks.hooks) {
      expect(h.action).toEqual({ type: 'command', command: `${nodeLine(cli)} hook --source workspace` });
      expect(h.matcher).toBeUndefined();
    }
    expect(hookCommand()).toBe(hooks.hooks[0].action.command);

    const agent = json(join(k, 'agents', 'kopt-explorer.json'));
    expect(agent.model).toBe('claude-haiku-4.5');
    expect(agent.tools).not.toContain('@kopt/kopt_run');
    expect(agent.includeMcpJson).toBe(true);

    const steering = read(join(k, 'steering', 'kopt.md'));
    expect(steering.startsWith('---\ninclusion: always\n---\n')).toBe(true);
    expect(steering.split(/\s+/).filter(Boolean).length).toBeLessThanOrEqual(60);
    // "who calls X" goes to kopt_refs, not to a pack
    expect(steering).toMatch(/Who calls\/uses X: `kopt_refs X`/);
    expect(read(join(k, 'steering', 'kopt-specs.md'))).toMatch(/^---\ninclusion: auto\nname: kopt-specs\ndescription: .+\n---\n/);

    const ki = read(join(root, '.kiroignore'));
    expect(ki.startsWith('# secrets\n.env\n')).toBe(true);
    expect(ki).not.toContain('/.kopt/'); // the index lives in the user cache dir
    expect(ki).toMatch(/# >>> kopt \(generated\)[^\n]*\n(.*\n)*yarn\.lock\n(.*\n)*# <<< kopt\n$/);
    expect(read(join(root, '.gitignore'))).toBe('node_modules/'); // nothing to ignore: no .kopt in the repo
    expect(existsSync(join(root, '.kopt'))).toBe(false);
    const vs = read(join(root, '.vscode', 'settings.json'));
    expect(vs).toContain('// keep me');
    expect(parseJsonc(vs)).toEqual({ 'kiroAgent.agentIgnoreFiles': ['.kiroignore'], 'editor.tabSize': 2 });

    // idempotent
    const again = await installKiro({ root, scope: 'workspace' });
    expect(again.written).toEqual([]);
    expect(again.skipped.length).toBeGreaterThanOrEqual(7);
  });

  it('per-project mode (<root>/.kopt exists): ignores .kopt in git and in agent reads', async () => {
    const root = newRepo('ws-local');
    mkdirSync(join(root, '.kopt'));
    write(root, '.gitignore', 'node_modules/');
    await installKiro({ root, scope: 'workspace' });
    expect(read(join(root, '.gitignore'))).toBe('node_modules/\n.kopt/\n');
    expect(read(join(root, '.kiroignore'))).toContain('\n/.kopt/\n');
  });

  it('writes the bare kopt shim when kopt is on PATH', async () => {
    process.env.KOPT_HOOK_COMMAND = 'shim';
    const root = newRepo('ws-shim');
    await installKiro({ root, scope: 'workspace' });
    expect(json(join(root, '.kiro', 'settings', 'mcp.json')).mcpServers.kopt.args.slice(0, 1)).toEqual(process.platform === 'win32' ? [cli] : ['mcp']);
    expect(json(join(root, '.kiro', 'hooks', 'kopt.json')).hooks[2].action.command).toBe(`${process.platform === 'win32' ? 'kopt.cmd' : 'kopt'} hook --source workspace`);
  });

  it('dry run computes changes without writing anything', async () => {
    const root = newRepo('dry');
    const r = await installKiro({ root, scope: 'workspace', dryRun: true });
    expect(r.written.length).toBeGreaterThanOrEqual(6);
    expect(r.notes[0]).toMatch(/dry run/);
    for (const p of r.written) expect(existsSync(p), p).toBe(false);
  });

  it('keeps user-edited kopt files unless forced, but updates files it wrote itself', async () => {
    const root = newRepo('edits');
    await installKiro({ root, scope: 'workspace' });
    const steering = join(root, '.kiro', 'steering', 'kopt.md');
    writeFileSync(steering, '---\ninclusion: always\n---\nmy own rules\n');
    // explorer model change: agent file was written by us, so it is updated without --force
    const r = await installKiro({ root, scope: 'workspace', explorerModel: 'claude-sonnet-4.6' });
    expect(json(join(root, '.kiro', 'agents', 'kopt-explorer.json')).model).toBe('claude-sonnet-4.6');
    expect(read(steering)).toContain('my own rules');
    expect(r.notes.some((n) => n.includes('kopt.md') && n.includes('--force'))).toBe(true);
    await installKiro({ root, scope: 'workspace', force: true });
    expect(read(steering)).not.toContain('my own rules');
  });

  it('refreshes a stale kopt server entry while keeping user fields, and refuses to clobber invalid JSON', async () => {
    const root = newRepo('stale');
    write(root, '.kiro/settings/mcp.json', JSON.stringify({ mcpServers: { kopt: { command: '/old/node', args: ['/old/cli.js', 'mcp'], env: { A: '1' }, autoApprove: ['kopt_find'], disabled: false } } }));
    await installKiro({ root, scope: 'workspace' });
    const kopt = json(join(root, '.kiro', 'settings', 'mcp.json')).mcpServers.kopt;
    expect(kopt).toEqual({ command: NODE, args: [cli, 'mcp', '--root', root], env: { A: '1' }, autoApprove: ['kopt_find'], disabled: false, ...MCP_TIMEOUTS });

    const bad = newRepo('badjson');
    write(bad, '.kiro/settings/mcp.json', '{ "mcpServers": { oops');
    const r = await installKiro({ root: bad, scope: 'workspace' });
    expect(read(join(bad, '.kiro', 'settings', 'mcp.json'))).toBe('{ "mcpServers": { oops');
    expect(r.notes.some((n) => n.includes('not valid JSON'))).toBe(true);
    expect(existsSync(join(bad, '.kiro', 'hooks', 'kopt.json'))).toBe(true);
  });

  it('installs user-wide into ~/.kiro (same layout as kopt setup) with a global kiroignore and the IDE user setting', async () => {
    const root = newRepo('userscope');
    write(root, 'Cargo.lock', '# lock');
    write(root, 'data/big.csv', 'a,b\n'.repeat(80_000));
    if (hasGit()) git(root, 'add', '-A');
    const home = process.env.KOPT_KIRO_HOME!;
    const r = await installKiro({ root, scope: 'user' });
    const mcp = json(join(home, 'settings', 'mcp.json'));
    expect(mcp.mcpServers.kopt).toEqual({ command: NODE, args: [cli, 'mcp'], autoApprove: AUTO_APPROVE, ...MCP_TIMEOUTS });
    for (const rel of ['steering/kopt.md', 'hooks/kopt.json', 'agents/kopt-explorer.json', 'agents/kopt.json']) expect(existsSync(join(home, rel)), rel).toBe(true);
    expect(json(join(home, 'hooks', 'kopt.json')).hooks[0].action.command).toBe(`${nodeLine(cli)} hook --source global`);
    const global = read(join(home, 'settings', 'kiroignore'));
    // user-wide: build artifacts only; a lockfile may need agent writes (merge conflicts), so it is per project
    expect(global).not.toContain('Cargo.lock');
    expect(global).toContain('*.min.js');
    expect(global).not.toContain('/data/big.csv');
    expect(json(process.env.KOPT_KIRO_USER_SETTINGS!)).toEqual({ 'kiroAgent.agentIgnoreFiles': ['.kiroignore'] });
    expect(existsSync(join(root, '.kiro'))).toBe(false);
    expect(existsSync(join(root, '.kiroignore'))).toBe(false);
    expect(r.written.every((p) => !p.startsWith(root + '/'))).toBe(true);
  });
});
